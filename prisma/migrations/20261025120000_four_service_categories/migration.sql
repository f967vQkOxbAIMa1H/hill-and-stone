-- Revision 1: six service categories become four. Existing leads and projects are mapped:
--   GENERAL_REPAIRS, CARPENTRY_DOORS_TRIM, DRYWALL_PAINTING, FLOORING_FIXTURES_HARDWARE -> INTERIOR_REPAIRS
--   EXTERIOR_REPAIRS -> EXTERIOR_REPAIRS
--   RENOVATIONS_CUSTOM -> HOME_IMPROVEMENTS
--   OTHER -> OTHER
-- PROPERTY_MAINTENANCE is new; nothing maps to it.

CREATE TYPE "ServiceCategory_new" AS ENUM ('INTERIOR_REPAIRS', 'EXTERIOR_REPAIRS', 'PROPERTY_MAINTENANCE', 'HOME_IMPROVEMENTS', 'OTHER');

ALTER TABLE "Lead" ALTER COLUMN "category" TYPE "ServiceCategory_new" USING (
  CASE "category"::text
    WHEN 'GENERAL_REPAIRS' THEN 'INTERIOR_REPAIRS'
    WHEN 'CARPENTRY_DOORS_TRIM' THEN 'INTERIOR_REPAIRS'
    WHEN 'DRYWALL_PAINTING' THEN 'INTERIOR_REPAIRS'
    WHEN 'FLOORING_FIXTURES_HARDWARE' THEN 'INTERIOR_REPAIRS'
    WHEN 'RENOVATIONS_CUSTOM' THEN 'HOME_IMPROVEMENTS'
    ELSE "category"::text
  END
)::"ServiceCategory_new";

ALTER TABLE "Project" ALTER COLUMN "category" TYPE "ServiceCategory_new" USING (
  CASE "category"::text
    WHEN 'GENERAL_REPAIRS' THEN 'INTERIOR_REPAIRS'
    WHEN 'CARPENTRY_DOORS_TRIM' THEN 'INTERIOR_REPAIRS'
    WHEN 'DRYWALL_PAINTING' THEN 'INTERIOR_REPAIRS'
    WHEN 'FLOORING_FIXTURES_HARDWARE' THEN 'INTERIOR_REPAIRS'
    WHEN 'RENOVATIONS_CUSTOM' THEN 'HOME_IMPROVEMENTS'
    ELSE "category"::text
  END
)::"ServiceCategory_new";

DROP TYPE "ServiceCategory";
ALTER TYPE "ServiceCategory_new" RENAME TO "ServiceCategory";
